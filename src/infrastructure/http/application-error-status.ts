import { HttpStatus } from '@nestjs/common';
import { ApplicationError, type ApplicationErrorCode } from '@/common/errors/application.error';

const HTTP_STATUS_BY_ERROR_CODE: Record<ApplicationErrorCode, HttpStatus> = {
  INVALID_MONEY: HttpStatus.BAD_REQUEST,
  CURRENCY_MISMATCH: HttpStatus.UNPROCESSABLE_ENTITY,
  INVALID_WALLET: HttpStatus.BAD_REQUEST,
  INSUFFICIENT_FUNDS: HttpStatus.UNPROCESSABLE_ENTITY,
  INVALID_WALLET_MOVEMENT: HttpStatus.BAD_REQUEST,
  INVALID_WALLET_LEDGER_ENTRY: HttpStatus.INTERNAL_SERVER_ERROR,
  WALLET_ALREADY_EXISTS: HttpStatus.CONFLICT,
  INVALID_PERSISTED_WALLET_STATE: HttpStatus.INTERNAL_SERVER_ERROR,
  WAGER_RESERVATION_CONFLICT: HttpStatus.CONFLICT,
  WAGER_IDEMPOTENCY_CONFLICT: HttpStatus.CONFLICT,
  WAGER_EXTERNAL_TRANSACTION_CONFLICT: HttpStatus.CONFLICT,
  WAGER_WALLET_NOT_FOUND: HttpStatus.NOT_FOUND,
  WAGER_WALLET_MISMATCH: HttpStatus.UNPROCESSABLE_ENTITY,
  INVALID_WAGER_AMOUNT: HttpStatus.BAD_REQUEST,
  WAGER_REFERENCE_NOT_FOUND: HttpStatus.NOT_FOUND,
  WAGER_REFERENCE_MISMATCH: HttpStatus.UNPROCESSABLE_ENTITY,
  INVALID_WAGER_TRANSACTION: HttpStatus.BAD_REQUEST,
  INVALID_WAGER_TRANSACTION_STATE: HttpStatus.CONFLICT,
  INVALID_PERSISTED_WAGER_RESULT: HttpStatus.INTERNAL_SERVER_ERROR,
  INVALID_WAGER_PROCESSING_STATE: HttpStatus.INTERNAL_SERVER_ERROR,
  INVALID_WAGER_UNIT_OF_WORK_STATE: HttpStatus.INTERNAL_SERVER_ERROR,
  INBOX_MESSAGE_CONFLICT: HttpStatus.CONFLICT,
  TRANSIENT_INFRASTRUCTURE_FAILURE: HttpStatus.SERVICE_UNAVAILABLE,
};

export function getHttpStatusForApplicationError(error: ApplicationError): HttpStatus {
  return HTTP_STATUS_BY_ERROR_CODE[error.code];
}
